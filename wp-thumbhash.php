namespace Hirasso\WPThumbhash;

/** Exit if accessed directly */
if (! defined('ABSPATH')) {
    exit;
}

/**
 * Autoload this plugin's own classes.
 * By hand, because a composer install has no plugin-local vendor/ and the release zip has no root autoloader.
 */
spl_autoload_register(static function (string $class): void {
    if (! str_starts_with($class, __NAMESPACE__.'\\')) {
        return;
    }

    $relative = substr($class, strlen(__NAMESPACE__) + 1);

    /** Prefixed dependencies share the namespace, but Strauss autoloads them */
    if (str_starts_with($relative, 'Vendor\\')) {
        return;
    }

    $file = __DIR__.'/src/'.str_replace('\\', '/', $relative).'.php';

    if (is_readable($file)) {
        require_once $file;
    }
});

/** Prefixed dependencies, generated by Strauss and committed */
require_once __DIR__.'/vendor-prefixed/autoload.php';

/** Get the plugin's base URL */
function baseURL(): string
{
    return plugins_url('', __FILE__);
}

/** Get the plugin's base directory */
function baseDir(): string
{
    return __DIR__;
}

